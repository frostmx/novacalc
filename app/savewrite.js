// Writing the architect's layout back into a save (no DOM; runs under Node for testing).
//
// The save is kept as a lossless tree: every node is { t, v } with the format's tag (1 list, 2 dict, 3 string,
// 4 int32, 5 int64, 6 bool, 7 float32, 8 float64); a dict's v is [[key, node], …] in file order. Untouched parts
// re-encode byte for byte. Rules checked in game on test worlds (CLAUDE.md "Writing saves"):
//  - the game loads buildings where the save puts them (no placement check) and keeps our ids;
//  - a new building must be a complete record: a copy of one of the same type with a new id and empty inventories;
//  - moving to another island = moving the record between the areas' Buildings lists; an Advanced Farm takes its
//    inner plots along, a plot its plant (Crop copy + the plant prop);
//  - recipe change = RecipeId (old items drop on the ground at load); bot tasks are regenerated by the game;
//  - a drone base lists its target containers (TargetContainers, ids) and carries a copy of its drone (DroneData);
//  - magnetoids: the island's Magnetoid Antenna lists them (AntennaMagnetoids: id, midpoint x/y, Origin/Target ids,
//    OriginSlot/TargetSlot, Horizontal), and each linked building has the id in Magnetoids[slot] ("null" = free).

import { bunzip2 } from './save.js';
import { bzip2 } from './bzip2.js';

// ---------- lossless tree ----------

export function readTree(text) {
  const bin = atob(text.trim());
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const b = bunzip2(bytes);
  const view = new DataView(b.buffer, b.byteOffset, b.byteLength);
  const utf8 = new TextDecoder('utf-8');
  let p = 0;
  const u7 = () => {
    let r = 0;
    for (let s = 0; ; s += 7) { const c = b[p++]; r |= (c & 0x7f) << s; if (!(c & 0x80)) return r; }
  };
  const str = () => { const n = u7(); const s = utf8.decode(b.subarray(p, p + n)); p += n; return s; };
  const val = () => {
    const t = b[p++];
    switch (t) {
      case 1: { const n = view.getInt32(p, true); p += 4; const a = new Array(n); for (let i = 0; i < n; i++) a[i] = val(); return { t, v: a }; }
      case 2: { const n = view.getInt32(p, true); p += 4; const a = new Array(n); for (let i = 0; i < n; i++) { const k = str(); a[i] = [k, val()]; } return { t, v: a }; }
      case 3: return { t, v: str() };
      case 4: { const v = view.getInt32(p, true); p += 4; return { t, v }; }
      case 5: { const v = view.getBigInt64(p, true); p += 8; return { t, v }; }
      case 6: return { t, v: b[p++] };
      case 7: { const v = view.getFloat32(p, true); p += 4; return { t, v }; }
      case 8: { const v = view.getFloat64(p, true); p += 8; return { t, v }; }
      default: throw new Error(`save: unknown tag ${t} at ${p - 1}`);
    }
  };
  const root = val();
  if (p !== b.length) throw new Error('save: trailing data');
  return root;
}

export function encodeTree(root) {
  let buf = new Uint8Array(1 << 20);
  let view = new DataView(buf.buffer);
  let len = 0;
  const utf8 = new TextEncoder();
  const room = n => {
    if (len + n <= buf.length) return;
    const nb = new Uint8Array(Math.max(buf.length * 2, len + n));
    nb.set(buf.subarray(0, len));
    buf = nb; view = new DataView(buf.buffer);
  };
  const byte = x => { room(1); buf[len++] = x; };
  const str = s => {
    const e = utf8.encode(s);
    let n = e.length;
    do { let c = n & 0x7f; n >>>= 7; if (n) c |= 0x80; byte(c); } while (n);
    room(e.length); buf.set(e, len); len += e.length;
  };
  const enc = node => {
    byte(node.t);
    switch (node.t) {
      case 1: room(4); view.setInt32(len, node.v.length, true); len += 4; for (const x of node.v) enc(x); break;
      case 2: room(4); view.setInt32(len, node.v.length, true); len += 4; for (const [k, x] of node.v) { str(k); enc(x); } break;
      case 3: str(node.v); break;
      case 4: room(4); view.setInt32(len, node.v, true); len += 4; break;
      case 5: room(8); view.setBigInt64(len, BigInt(node.v), true); len += 8; break;
      case 6: byte(node.v ? 1 : 0); break;
      case 7: room(4); view.setFloat32(len, node.v, true); len += 4; break;
      case 8: room(8); view.setFloat64(len, node.v, true); len += 8; break;
      default: throw new Error(`save: bad tag ${node.t}`);
    }
  };
  enc(root);
  return buf.subarray(0, len);
}

/** Save file text (base64 of bzip2 of the tree). */
export function writeTree(root) {
  const z = bzip2(encodeTree(root));
  let s = '';
  for (let i = 0; i < z.length; i += 0x8000) s += String.fromCharCode(...z.subarray(i, i + 0x8000));
  return btoa(s);
}

// node helpers
const child = (n, k) => n?.t === 2 ? n.v.find(e => e[0] === k)?.[1] : undefined;
const value = (n, k) => { const c = child(n, k); return c && c.t >= 3 ? (c.t === 5 ? Number(c.v) : c.v) : undefined; };
function set(n, k, v) {
  const c = child(n, k);
  if (c) c.v = c.t === 5 ? BigInt(v) : v;
}
const listOf = (n, k) => { const c = child(n, k); return c?.t === 1 ? c.v : null; };
function ensureList(n, k) {
  let c = child(n, k);
  if (!c) { c = { t: 1, v: [] }; n.v.push([k, c]); }
  return c.v;
}
const clone = n => (n.t === 1 ? { t: 1, v: n.v.map(clone) } : n.t === 2 ? { t: 2, v: n.v.map(([k, x]) => [k, clone(x)]) } : { ...n });
const str = v => ({ t: 3, v });
const int = v => ({ t: 4, v });
const emptySlot = () => ({ t: 2, v: [['Resource', int(-1)], ['Amount', int(0)], ['ExtraData', str('')]] });

function* walk(n) {
  yield n;
  if (n.t === 1) for (const x of n.v) yield* walk(x);
  else if (n.t === 2) for (const [, x] of n.v) yield* walk(x);
}

// ---------- what may be edited ----------

// Buildings the game does not let the player move (canBeMoved false) but that are plain player buildings
const EXTRA_EDITABLE = new Set(['Antenna', 'BatterySmall', 'Container', 'TransporterContainerInput', 'TransporterContainerOutput',
  'ExtractorTower', 'DataAnalyzer', 'BiomeScanner', 'AnimalRegisterComputer', 'AnimalBarnMonitorBuilding']);

/** May the editor move / delete / add this building type (NPCs, shops, landmarks: no)? */
export const editableBuilding = b => !!b?.footprint && (!!b.movable || EXTRA_EDITABLE.has(b.key));

/** Areas of the save (not the out-of-map ring). */
function areasOf(root) {
  const out = [];
  const world = child(child(root, 'World'), 'World');
  for (const [, layer] of world?.v ?? []) for (const a of layer.v) if (value(a, 'OutOfMap') !== 'True') out.push(a);
  return out;
}

/** Building types the save has a complete record of (new buildings are copies of one). */
export function templateTypes(root) {
  const ids = new Set();
  for (const a of areasOf(root)) {
    for (const b of listOf(a, 'Buildings') ?? []) if (value(b, 'IsInnerFarmPlot') !== 'True') ids.add(value(b, 'BuildingId'));
  }
  return [...ids];
}

// ---------- applying the layout ----------

const near = (a, b) => Math.abs(a - b) < 0.01;

/**
 * Apply the plan to a save tree (in place). `plan`:
 *  placed: [{ id, b, g, x, y, uid?, node?, slot?, twin?, item? }] (x, y relative to the island centre),
 *  props: [{ uid, g, x, y }], magnets: [{ uid?, from, to, fs, ts }], nodes: [{ id, r, … }],
 *  groups: { g: { q, r, premade?, locked? } }, db: { buildings: Map, footprintOf, magnetAntennaId },
 *  hexAt(x, y) -> { q, r } (the island slot of a world point).
 * Islands are matched by group key `i<areaId>`. Returns a summary { moved, transferred, added, deleted, recipes,
 * items, props, skipped: [{ reason, b }] }.
 */
export function applyLayout(root, plan) {
  const { db } = plan;
  const sum = { moved: 0, transferred: 0, added: 0, deleted: 0, recipes: 0, items: 0, props: 0, drones: 0, magnets: 0, skipped: [] };
  const skip = (reason, b) => sum.skipped.push({ reason, b });
  const areas = areasOf(root);
  const areaById = new Map(areas.map(a => [value(a, 'Id'), a]));
  const nodes = new Map(plan.nodes.map(n => [n.id, n]));

  // an island of the plan is written only when it is the save's island on the same hex slot and is not premade/locked
  const editableArea = new Map();
  for (const [g, grp] of Object.entries(plan.groups)) {
    const a = /^i-?\d+$/.test(g) ? areaById.get(Number(g.slice(1))) : null;
    if (!a || grp.q == null || value(a, 'Premade') === 'True' || value(a, 'Locked') === 'True') continue;
    const h = plan.hexAt(value(a, 'X'), value(a, 'Y'));
    if (h.q !== grp.q || h.r !== grp.r) continue;
    editableArea.set(g, a);
  }
  const areaKey = a => `i${value(a, 'Id')}`;
  const isEditable = a => editableArea.get(areaKey(a)) === a;

  // records by id, inner plots by farm, plant props by id
  const recs = new Map(); // id -> { a, rec }
  for (const a of areas) for (const rec of listOf(a, 'Buildings') ?? []) recs.set(value(rec, 'Id'), { a, rec });
  // an Advanced Farm lists its inner plots by id (FarmPlots), in slot order; a copy must list its own new plots
  const innerPlots = (a, farm) => (listOf(farm, 'FarmPlots') ?? [])
    .map(n => recs.get(n.t === 5 ? Number(n.v) : n.v)).filter(r => r && r.a === a).map(r => r.rec);
  const plantOf = (a, plot) => {
    const id = value(child(plot, 'Crop'), 'Id');
    return id == null ? null : (listOf(a, 'Props') ?? []).find(p => value(p, 'Id') === id) ?? null;
  };

  // ids: any int not used anywhere in the save, counting down from -9000001
  const usedInts = new Set();
  for (const n of walk(root)) if (n.t === 4) usedInts.add(n.v);
  let nextId = -9000001;
  const newId = () => { while (usedInts.has(nextId)) nextId--; usedInts.add(nextId); return nextId--; };

  // name counters: "DEPOSIT AREA-53" takes Indexes[BuildingId] and bumps it
  const indexes = new Map((listOf(root, 'Indexes') ?? []).map(e => [value(e, 'BuildingId'), e]));
  const nameFor = (tmpl, b) => {
    const name = value(tmpl, 'Name') ?? '';
    const m = /^(.*)-(\d+)$/.exec(name);
    const e = indexes.get(b);
    if (!m || !e) return name;
    const i = value(e, 'Index');
    set(e, 'Index', i + 1);
    return `${m[1]}-${String(i).padStart(m[2].length, '0')}`;
  };

  const worldOf = (a, p) => {
    if (p.slot != null) {
      const s = listOf(a, 'TransportersSlots')?.[p.slot];
      if (s) return { x: value(s, 'X'), y: value(s, 'Y') };
    }
    return { x: value(a, 'X') + p.x, y: value(a, 'Y') + p.y };
  };

  const moveRec = (rec, from, to, dx, dy) => {
    set(rec, 'X', value(rec, 'X') + dx);
    set(rec, 'Y', value(rec, 'Y') + dy);
    const crop = child(rec, 'Crop');
    if (crop?.t === 2 && value(crop, 'X') != null) { set(crop, 'X', value(crop, 'X') + dx); set(crop, 'Y', value(crop, 'Y') + dy); }
    const plant = plantOf(from, rec);
    if (plant) {
      set(plant, 'X', value(plant, 'X') + dx);
      set(plant, 'Y', value(plant, 'Y') + dy);
      if (to !== from) { const l = listOf(from, 'Props'); l.splice(l.indexOf(plant), 1); ensureList(to, 'Props').push(plant); }
    }
    if (to !== from) {
      const l = listOf(from, 'Buildings');
      l.splice(l.indexOf(rec), 1);
      ensureList(to, 'Buildings').push(rec);
    }
  };
  const removeRec = (rec, a) => {
    const plant = plantOf(a, rec);
    if (plant) { const l = listOf(a, 'Props'); l.splice(l.indexOf(plant), 1); }
    const l = listOf(a, 'Buildings');
    l.splice(l.indexOf(rec), 1);
  };

  // templates for new buildings (taken before anything moves): a record of the type with its inner plots
  const templates = new Map();
  for (const { a, rec } of recs.values()) {
    if (value(rec, 'IsInnerFarmPlot') === 'True') continue;
    const id = value(rec, 'BuildingId');
    const cur = templates.get(id);
    if (!cur || (value(cur.a, 'Premade') === 'True' && value(a, 'Premade') !== 'True')) templates.set(id, { a, rec });
  }
  for (const t of templates.values()) {
    const b = db.buildings.get(value(t.rec, 'BuildingId'));
    t.plots = b?.farm ? innerPlots(t.a, t.rec).map(clone) : [];
    t.rec = clone(t.rec);
  }
  const seedling = [...recs.values()].map(({ rec }) => child(rec, 'Crop'))
    .find(c => c?.t === 2 && value(c, 'Name') === 'BaseCropBuilding(Clone)');

  // ids for this write: the save's own for buildings it has, fresh ones for new buildings
  const placed = plan.placed.filter(p => editableArea.has(p.g));
  for (const p of plan.placed) if (!editableArea.has(p.g) && !recs.has(p.uid)) skip('island', p.b); // new, can't be written
  const uidOf = new Map();
  const isNew = new Set();
  for (const p of placed) {
    const r = p.uid != null ? recs.get(p.uid) : null;
    if (r && isEditable(r.a)) { uidOf.set(p.id, p.uid); continue; }
    if (!templates.has(p.b) || !editableBuilding(db.buildings.get(p.b))) { skip('template', p.b); continue; }
    uidOf.set(p.id, newId());
    isNew.add(p.id);
  }
  const byUid = new Map(placed.filter(p => uidOf.has(p.id) && !isNew.has(p.id)).map(p => [p.uid, p]));
  const goneUids = new Set();

  // 1. existing buildings: delete or move (an Advanced Farm with its inner plots, a plot with its plant)
  for (const [uid, { a, rec }] of recs) {
    if (!isEditable(a) || value(rec, 'IsInnerFarmPlot') === 'True') continue;
    const b = db.buildings.get(value(rec, 'BuildingId'));
    if (!editableBuilding(b)) continue;
    const p = byUid.get(uid);
    const plots = b.farm ? innerPlots(a, rec) : [];
    if (!p) {
      for (const r of [rec, ...plots]) { removeRec(r, a); goneUids.add(value(r, 'Id')); }
      sum.deleted++;
      continue;
    }
    const to = editableArea.get(p.g);
    const w = worldOf(to, p);
    const dx = w.x - value(rec, 'X'); const dy = w.y - value(rec, 'Y');
    if (to === a && near(dx, 0) && near(dy, 0)) continue;
    for (const r of [rec, ...plots]) moveRec(r, a, to, dx, dy);
    if (p.slot != null) { set(rec, 'X', w.x); set(rec, 'Y', w.y); } // exact slot position
    if (to !== a) { sum.transferred++; for (const r of [rec, ...plots]) goneUids.add(value(r, 'Id')); } else sum.moved++;
  }

  // 2. new buildings: copies of a record of the same type
  const fresh = (tmpl, x, y, id) => {
    const rec = clone(tmpl);
    set(rec, 'Id', id);
    set(rec, 'Name', nameFor(tmpl, value(tmpl, 'BuildingId')));
    set(rec, 'X', x); set(rec, 'Y', y);
    resetRecord(rec);
    const drone = child(rec, 'DroneData');
    if (drone?.t === 2) { // a new drone base: its own idle, empty drone at home
      set(drone, 'Id', newId()); set(drone, 'X', x); set(drone, 'Y', y);
      set(drone, 'State', 'CharacterIdle'); set(drone, 'Target', -1); set(drone, 'TargetName', value(rec, 'Name'));
      set(drone, 'CurrentTargetContainer', 0);
      for (const c of listOf(drone, 'CarriedResources') ?? []) set(c, 'Amount', 0);
      const tc = child(rec, 'TargetContainers');
      if (tc) tc.v = [];
    }
    if (child(rec, 'Crop')?.t === 2) { // a plot starts with a fresh seedling of its seed
      if (!seedling) return null;
      const c = clone(seedling);
      set(c, 'Id', newId()); set(c, 'X', x); set(c, 'Y', y + 0.1);
      set(c, 'GrowthTime', 0); set(c, 'CurrentTotalGrowthTime', 0); set(c, 'GrowthState', 0);
      set(c, 'Seed', value(rec, 'Seed'));
      rec.v[rec.v.findIndex(e => e[0] === 'Crop')][1] = c;
    }
    return rec;
  };
  for (const p of placed) {
    if (!isNew.has(p.id)) continue;
    const t = templates.get(p.b);
    const to = editableArea.get(p.g);
    const w = worldOf(to, p);
    const ox = value(t.rec, 'X'); const oy = value(t.rec, 'Y');
    const out = [fresh(t.rec, w.x, w.y, uidOf.get(p.id)),
      ...t.plots.map(r => fresh(r, w.x + value(r, 'X') - ox, w.y + value(r, 'Y') - oy, newId()))];
    if (out.some(r => !r)) { skip('template', p.b); uidOf.delete(p.id); continue; }
    const plotIds = child(out[0], 'FarmPlots');
    if (plotIds) plotIds.v = out.slice(1).map(r => ({ t: 4, v: value(r, 'Id') }));
    ensureList(to, 'Buildings').push(...out);
    sum.added++;
  }

  // 3. the card's recipe, what a transporter carries and which arm is its twin
  const recByUid = new Map();
  for (const a of editableArea.values()) for (const rec of listOf(a, 'Buildings') ?? []) recByUid.set(value(rec, 'Id'), rec);
  const placedById = new Map(placed.map(p => [p.id, p]));
  const planById = new Map(plan.placed.map(p => [p.id, p]));
  for (const p of placed) {
    const rec = recByUid.get(uidOf.get(p.id));
    if (!rec) continue;
    const n = p.node != null ? nodes.get(p.node) : null;
    const recipe = n && n.r == null ? -1 : n?.r; // a card with no recipe: RecipeId -1
    if (n && typeof recipe === 'number' && child(rec, 'RecipeId') && value(rec, 'RecipeId') !== recipe) {
      set(rec, 'RecipeId', recipe);
      if (!isNew.has(p.id)) sum.recipes++;
    }
    const t = p.twin != null ? placedById.get(p.twin) : null;
    const tc = child(rec, 'TwinContainer');
    if (t && tc && uidOf.has(t.id)) {
      if (value(tc, 'Id') !== uidOf.get(t.id)) set(tc, 'Id', uidOf.get(t.id));
      const area = value(editableArea.get(t.g), 'Id');
      if (value(tc, 'Area') !== area) set(tc, 'Area', area);
    }
    if (p.item != null && child(rec, 'RequiredResource') && value(rec, 'RequiredResource') !== p.item) {
      set(rec, 'RequiredResource', p.item);
      if (!isNew.has(p.id)) sum.items++;
    }
    const targets = child(rec, 'TargetContainers');
    if (targets?.t === 1 && p.targets) {
      const want = p.targets.map(id => uidOf.get(id) ?? planById.get(id)?.uid).filter(u => u != null && (recs.has(u) || recByUid.has(u)));
      const cur = targets.v.map(n => n.v);
      if (want.length !== cur.length || want.some((u, i) => u !== cur[i])) {
        targets.v = want.map(int);
        if (!isNew.has(p.id)) sum.drones++;
      }
    }
  }

  // 4. magnetoids, island by island (only where the island has a Magnetoid Antenna)
  const goneMagnets = new Set();
  const magnetTemplate = (() => {
    for (const { rec } of recs.values()) { const e = listOf(rec, 'AntennaMagnetoids')?.[0]; if (e) return e; }
    return null;
  })();
  // (a plan without `magnets` comes from a board that never read them: leave the save's magnetoids alone)
  for (const area of plan.magnets ? editableArea.values() : []) {
    const blds = listOf(area, 'Buildings') ?? [];
    const antenna = blds.find(r => value(r, 'BuildingId') === db.magnetAntennaId);
    if (!antenna) continue;
    const list = ensureList(antenna, 'AntennaMagnetoids');
    const want = [];
    for (const m of plan.magnets ?? []) {
      const a = placedById.get(m.from); const c = placedById.get(m.to);
      if (!a || !c || editableArea.get(a.g) !== area || editableArea.get(c.g) !== area) continue;
      const ua = uidOf.get(a.id); const uc = uidOf.get(c.id);
      if (ua == null || uc == null) continue;
      want.push({ m, a, c, ua, uc });
    }
    const have = new Map(list.map(e => [value(e, 'Id'), e]));
    const keep = new Set(want.filter(w => w.m.uid != null && have.has(w.m.uid)).map(w => w.m.uid));
    for (const id of have.keys()) if (!keep.has(id)) { goneMagnets.add(id); sum.magnets++; }
    const kept = list.filter(e => keep.has(value(e, 'Id')));
    // new ones: next ids of this antenna's counter
    let counter = value(antenna, 'CurrentMagnetoidId') ?? -2147483648;
    const taken = new Set([...have.keys()]);
    for (const w of want) {
      if (w.m.uid != null && keep.has(w.m.uid)) { w.id = w.m.uid; continue; }
      while (taken.has(counter)) counter++; // ids are per antenna (island), like the game counts them
      w.id = counter++;
      taken.add(w.id);
      const ba = db.buildings.get(w.a.b); const bc = db.buildings.get(w.c.b);
      const ra = recByUid.get(w.ua); const rc = recByUid.get(w.uc);
      const sa = ba?.magnetSlots?.[w.m.fs]; const sc = bc?.magnetSlots?.[w.m.ts];
      if (!ra || !rc || !sa || !sc) { skip('magnet', w.a.b); w.id = null; continue; }
      const ax = value(ra, 'X') + sa[0]; const ay = value(ra, 'Y') + sa[1];
      const cx = value(rc, 'X') + sc[0]; const cy = value(rc, 'Y') + sc[1];
      const e = magnetTemplate ? clone(magnetTemplate) : { t: 2, v: [] };
      const put = (k, node) => { const i = e.v.findIndex(x => x[0] === k); if (i >= 0) e.v[i][1] = node; else e.v.push([k, node]); };
      put('Id', int(w.id));
      put('x', { t: 7, v: (ax + cx) / 2 }); put('y', { t: 7, v: (ay + cy) / 2 }); put('z', int(0));
      put('Origin', int(w.ua)); put('Target', int(w.uc));
      put('CurResource', str('')); put('Horizontal', str(Math.abs(cx - ax) >= Math.abs(cy - ay) ? 'True' : 'False'));
      put('Task', str('')); put('OriginSlot', int(w.m.fs)); put('TargetSlot', int(w.m.ts)); put('CurrentAccelerationTime', int(0));
      kept.push(e);
      sum.magnets++;
    }
    child(antenna, 'AntennaMagnetoids').v = kept;
    if (child(antenna, 'CurrentMagnetoidId')) set(antenna, 'CurrentMagnetoidId', counter);
    // slot marks on the buildings
    const mark = new Map();
    for (const w of want) {
      if (w.id == null) continue;
      mark.set(`${w.ua}|${w.m.fs}`, w.id);
      mark.set(`${w.uc}|${w.m.ts}`, w.id);
    }
    for (const rec of blds) {
      const slots = listOf(rec, 'Magnetoids');
      if (!slots) continue;
      slots.forEach((slot, i) => {
        const id = mark.get(`${value(rec, 'Id')}|${i}`);
        const cur = child(slot, 'Id');
        if (!cur) return;
        if (id != null) { if (cur.t !== 4 || cur.v !== id) slot.v[slot.v.findIndex(x => x[0] === 'Id')][1] = int(id); }
        else if (cur.t === 4 || cur.t === 5) slot.v[slot.v.findIndex(x => x[0] === 'Id')][1] = str('null');
      });
    }
  }

  // 5. bot tasks on buildings that left their island or are gone, or on removed magnetoids (the game makes new ones)
  for (const a of areas) {
    for (const rec of listOf(a, 'Buildings') ?? []) {
      for (const [k, lst] of rec.v) {
        if (!/^Tasks\d*$/.test(k) || lst.t !== 1) continue;
        lst.v = lst.v.filter(t => !goneUids.has(value(t, 'TargetBuilding')) && !goneUids.has(value(t, 'OriginContainer')));
        for (const t of lst.v) if (goneMagnets.has(value(t, 'AssignedMagnetoid'))) set(t, 'AssignedMagnetoid', '');
      }
    }
  }

  // 6. props (rocks, bushes, …) moved on their island
  for (const pr of plan.props ?? []) {
    const a = editableArea.get(pr.g);
    const rec = a && (listOf(a, 'Props') ?? []).find(x => value(x, 'Id') === pr.uid);
    if (!rec) continue;
    const x = value(a, 'X') + pr.x; const y = value(a, 'Y') + pr.y;
    if (near(x, value(rec, 'X')) && near(y, value(rec, 'Y'))) continue;
    set(rec, 'X', x); set(rec, 'Y', y);
    sum.props++;
  }
  return sum;
}

/** A copied record starts empty and idle: inventories, production, fuel, transport, bots, tasks. */
function resetRecord(rec) {
  for (const [k, n] of rec.v) {
    if (/Inventory$/.test(k) && n.t === 1) n.v = n.v.map(emptySlot);
    else if ((/^Tasks\d*$/.test(k) || k === 'Bots') && n.t === 1) n.v = [];
  }
  const reset = { CurrentProductionTime: 0, IsProducing: 'False', State: 'BuildingIdle', ConsumingFuel: 'False',
    CurrentFuelDuration: 0, TransportedAmount: 0, TransportedItem: -1, TransportationTime: 0 };
  for (const [k, v] of Object.entries(reset)) {
    const c = child(rec, k);
    if (c && (c.t === 3) === (typeof v === 'string')) c.v = v;
  }
  const max = value(rec, 'MaxHealth');
  if (max != null) set(rec, 'CurrentHealth', max);
}
